export function classificar(card: Card): { tema: Tema; nivel: Nivel } {
  const known = CLASSIFICACAO[card.meta.id]
  if (known) return { tema: known[0], nivel: known[1] }
  const palavras = card.meta.fraseAlvo.split(/\s+/).filter(Boolean).length
  return { tema: 'outros', nivel: palavras <= 3 ? 1 : palavras <= 6 ? 2 : 3 }
}
